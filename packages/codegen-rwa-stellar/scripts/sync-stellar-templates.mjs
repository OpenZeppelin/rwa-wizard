#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const packageRoot = path.resolve(__dirname, '..');
const manifestPath = path.join(packageRoot, 'src', 'upstream', 'template-manifest.json');
const outputPath = path.join(packageRoot, 'src', 'upstream', 'generated-snapshot.ts');
const revisionOutputPath = path.join(packageRoot, 'src', 'upstream', 'generated-revision.ts');

const SOURCE_REPO_URL_FALLBACK = 'https://github.com/OpenZeppelin/stellar-contracts.git';

function resolveCheckoutRoot() {
  const cliArg = process.argv[2];
  if (cliArg) return path.resolve(cliArg);

  const envPath = process.env.STELLAR_CONTRACTS_PATH;
  if (envPath) return path.resolve(envPath);

  return path.resolve(process.env.HOME ?? '', 'dev', 'repos', 'OpenZeppelin', 'stellar-contracts');
}

function loadManifest() {
  return JSON.parse(readFileSync(manifestPath, 'utf8'));
}

function getTemplateKey(entry) {
  return `${entry.kind}:${entry.id}`;
}

function readGitValue(checkoutRoot, args, fallback = '') {
  try {
    return execFileSync('git', args, {
      cwd: checkoutRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return fallback;
  }
}

function normalizeGitRemoteUrl(value) {
  if (!value) return SOURCE_REPO_URL_FALLBACK;

  if (value.startsWith('git@github.com:')) {
    const pathPart = value.slice('git@github.com:'.length).replace(/\.git$/, '');
    return `https://github.com/${pathPart}.git`;
  }

  try {
    const parsed = new URL(value);
    parsed.username = '';
    parsed.password = '';

    if (!parsed.pathname.endsWith('.git')) {
      parsed.pathname = `${parsed.pathname.replace(/\/+$/, '')}.git`;
    }

    return parsed.toString();
  } catch {
    return value;
  }
}

const CANONICAL_REPO_OWNER = 'OpenZeppelin';

function resolveSourceRepoUrl(checkoutRoot) {
  const originUrl = readGitValue(
    checkoutRoot,
    ['remote', 'get-url', 'origin'],
    SOURCE_REPO_URL_FALLBACK
  );
  const normalized = normalizeGitRemoteUrl(originUrl);

  try {
    const parsed = new URL(normalized);
    const owner = parsed.pathname.split('/').filter(Boolean)[0];
    if (owner !== CANONICAL_REPO_OWNER) {
      process.stderr.write(
        `Warning: checkout remote "${normalized}" is not under ${CANONICAL_REPO_OWNER}. ` +
        `Using canonical URL: ${SOURCE_REPO_URL_FALLBACK}\n`
      );
      return SOURCE_REPO_URL_FALLBACK;
    }
  } catch {
    return SOURCE_REPO_URL_FALLBACK;
  }

  return normalized;
}

function buildSnapshotMetadata(checkoutRoot) {
  return {
    sourceRepoUrl: resolveSourceRepoUrl(checkoutRoot),
    sourceCommitHash: readGitValue(checkoutRoot, ['rev-parse', 'HEAD']),
    syncedAt: new Date().toISOString(),
  };
}

function buildSnapshot(checkoutRoot, manifest) {
  const metadata = buildSnapshotMetadata(checkoutRoot);
  const templates = {};

  for (const entry of manifest) {
    const fullPath = path.join(checkoutRoot, entry.sourcePath);
    if (!existsSync(fullPath)) {
      throw new Error(`Missing upstream template source: ${fullPath}`);
    }

    templates[getTemplateKey(entry)] = {
      sourcePath: entry.sourcePath,
      content: readFileSync(fullPath, 'utf8'),
    };
  }

  return {
    metadata,
    templates,
  };
}

function renderSnapshotModule(snapshot) {
  return `/* eslint-disable */
// Auto-generated by scripts/sync-stellar-templates.mjs. Do not edit by hand.
import type { UpstreamTemplateSnapshot } from './types';

export const GENERATED_STELLAR_TEMPLATE_SNAPSHOT: UpstreamTemplateSnapshot = ${JSON.stringify(snapshot, null, 2)};\n`;
}

function renderRevisionModule(snapshot) {
  return `/* eslint-disable */
// Auto-generated by scripts/sync-stellar-templates.mjs. Do not edit by hand.

export const GENERATED_STELLAR_SOURCE_REPO_URL = ${JSON.stringify(snapshot.metadata.sourceRepoUrl)};
export const GENERATED_STELLAR_SOURCE_COMMIT_HASH = ${JSON.stringify(snapshot.metadata.sourceCommitHash)};
export const GENERATED_STELLAR_SOURCE_SYNCED_AT = ${JSON.stringify(snapshot.metadata.syncedAt)};
`;
}

function main() {
  const checkoutRoot = resolveCheckoutRoot();
  if (!existsSync(checkoutRoot)) {
    throw new Error(`stellar-contracts checkout not found: ${checkoutRoot}`);
  }

  const manifest = loadManifest();
  const snapshot = buildSnapshot(checkoutRoot, manifest);

  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, renderSnapshotModule(snapshot), 'utf8');
  writeFileSync(revisionOutputPath, renderRevisionModule(snapshot), 'utf8');

  process.stdout.write(
    `Synced ${Object.keys(snapshot.templates).length} upstream templates from ${checkoutRoot}\n`
  );
}

main();
